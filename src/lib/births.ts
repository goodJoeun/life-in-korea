/** 1990~1994년 그 지역 성비가 전국보다 얼마나 더 치우쳤는지 (남아선호가 강한 지역일수록 큼) */
function regionTilt(region: RegionId): number {
  const parent = region === 'ulsan' ? 'gyeongnam' : region === 'sejong' ? 'chungnam' : region;
  const reg = SRB_REGION[parent]!.slice(0, 5) as number[];
  const nat = [116.5, 112.4, 113.6, 115.3, 115.2];
  const avg = (a: number[]) => a.reduce((s, x) => s + x, 0) / a.length;
  return (avg(reg) - NATURAL) / (avg(nat) - NATURAL);
}

export function nationalSexRatio(year: number): number {
  return at(SRB_NATIONAL, year);
}

/**
 * year 년, region 에서 태어난 아이의 출생성비 (여아 100명당 남아).
 * 1990~2025: 그해 그 시도의 공표치. 울산·세종처럼 아직 없던 해에는 부모 도 값.
 * 1985~1989: 성감별이 퍼지던 시기라, 전국 값의 '자연성비 초과분'에 그 지역의 1990년대 초 치우침 정도를 곱한다. (추정)
 * 그 밖의 해: 전국 값.
 */
export function sexRatio(year: number, region?: RegionId): number {
  const nat = nationalSexRatio(year);
  if (!region || year > R1) return nat; // 2026년 이후는 시도별 값이 없어 전국 값
  if (year >= R0) {
    const i = year - R0;
    let v = SRB_REGION[region]?.[i];
    if (v == null && region === 'ulsan') v = SRB_REGION.gyeongnam![i];
    if (v == null && region === 'sejong') v = SRB_REGION.chungnam![i];
    return v ?? nat;
  }
  if (year >= 1985) return NATURAL + (nat - NATURAL) * regionTilt(region);
  return nat;
}

/**
 * 부모가 order 번째 아이를 year 년에 낳을 때의 출생성비.
 * (공식) 1981~2025 출산순위별 전국 값에, 사는 지역이 전국보다 얼마나 치우쳤는지를 곱한다.
 * 1981년 이전은 순위 구분 없이 전국 값.
 */
export function childSexRatio(year: number, order: number, region?: RegionId): number {
  if (year < B0) return sexRatio(year, region);
  const o = Math.min(Math.max(order, 1), 4) as 1 | 2 | 3 | 4;
  const byOrder = year > B1 ? nationalSexRatio(year) : SRB_ORDER[o][year - B0];
  if (!region) return byOrder;
  const nat = nationalSexRatio(year);
  const reg = sexRatio(year, region);
  // 지역 치우침은 '자연성비 초과분의 배율'로 옮긴다. 전국 초과분이 거의 없으면 지역 값 차이만 더한다.
  const excess = nat - NATURAL;
  const factor = excess > 1 ? (reg - NATURAL) / excess : 1;
  return Math.max(95, excess > 1 ? NATURAL + (byOrder - NATURAL) * factor : byOrder + (reg - nat));
}

